#!/usr/bin/env node
// Writes render.env (git-ignored): every environment variable the Render service needs, in .env format, for pasting into
// Render's "Add from .env". Secret values are copied from your local .env and are NEVER printed; only variable names are.
//   pnpm render:env
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const envFile = path.join(root, ".env");
if (!existsSync(envFile)) {
  console.error("render:env: no .env found. Create it first (see README).");
  process.exit(1);
}
const local = Object.fromEntries(
  readFileSync(envFile, "utf8")
    .split(/\r?\n/)
    .map((l) => l.match(/^([A-Z0-9_]+)=(.*)$/))
    .filter(Boolean)
    .map((m) => [m[1], m[2].replace(/^"(.*)"$/, "$1")]),
);

/** Copied from the local .env. `secret` only changes how the summary describes them. */
const FROM_LOCAL = [
  ["PAYPAL_CLIENT_ID", true],
  ["PAYPAL_CLIENT_SECRET", true],
  ["PURSER_ADMIN_TOKEN", true],
  ["AGENT_API_KEY", true],
  ["LLM_API_KEY", true],
  ["BUSINESS_EMAIL", false],
  ["VENDOR_ACME_EMAIL", false],
  ["VENDOR_NORTHWIND_EMAIL", false],
  ["LLM_PROVIDER", false],
  ["LLM_BASE_URL", false],
  ["LLM_MODEL", false],
  ["LLM_REASONING_EFFORT", false],
];
/** Fixed for the deployment, whatever the local .env says. */
const FIXED = {
  NODE_ENV: "production",
  PAYPAL_ENV: "sandbox",
  UPSTREAM_MODE: "stdio",
  AI_MODE: "live",
  AI_CACHE_TTL_SEC: "31536000",
  DATABASE_PATH: "./data/purser.db",
  LOG_LEVEL: "info",
};

/** Used when the local .env does not set the variable. */
const DEFAULTS = { LLM_REASONING_EFFORT: "low" };

const lines = ["# Generated by `pnpm render:env`. Contains secrets: git-ignored, never commit or share it.", "# Paste into Render > Environment > Add from .env. PUBLIC_URL is left out on purpose (RENDER_EXTERNAL_URL is the fallback).", "# PAYPAL_WEBHOOK_ID is added later, after the webhook is registered for the live URL."];
const missing = [];
for (const [k] of FROM_LOCAL) {
  const v = local[k] || DEFAULTS[k];
  if (!v) missing.push(k);
  else lines.push(`${k}=${v}`);
}
for (const [k, v] of Object.entries(FIXED)) lines.push(`${k}=${v}`);
writeFileSync(path.join(root, "render.env"), lines.join("\n") + "\n");

const written = lines.filter((l) => !l.startsWith("#")).map((l) => l.split("=")[0]);
console.log(`render:env: wrote render.env with ${written.length} variables (values not shown):`);
console.log("  " + written.join(", "));
if (missing.length) console.log(`render:env: NOT in your .env, so not written: ${missing.join(", ")}`);
process.exitCode = missing.length ? 1 : 0;
